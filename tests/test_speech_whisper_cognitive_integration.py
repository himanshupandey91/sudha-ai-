"""
Sudha AI - Real Whisper to Cognitive Experiment Integration

Step 64-B

Validates the real runtime path:

Real Audio
    ↓
Whisper.cpp CLI
    ↓
WhisperCLIBackend
    ↓
SpeechRecognitionEngine
    ↓
Real Transcription
    ↓
Cognitive Experiment
    ↓
Hypothesis Selection
    ↓
Prediction
    ↓
Observed Outcome
    ↓
Prediction Error
    ↓
Hypothesis-Specific Learning
    ↓
NEXT CYCLE
    ↓
Changed Prediction

This test intentionally uses:

- real whisper.cpp executable
- real tiny.en model
- real JFK sample audio
- real CognitiveExperimentEngine
- real AdaptivePredictor learning

No deterministic speech mock is used at the
speech-recognition boundary.

The observed outcome used for the cognitive experiment
is explicitly derived from the real Whisper transcription.
It is never generated by the predictor itself.
"""

from pathlib import Path

from core.cognitive_experiment import (
    CognitiveExperimentEngine
)
from core.cognitive_pipeline import CognitivePipeline
from core.hypothesis import HypothesisEngine
from core.hypothesis_planner import (
    HypothesisPlanningEngine
)
from core.speech_recognition import (
    SpeechRecognitionEngine
)
from core.whisper_cli_backend import (
    WhisperCLIBackend
)


ROOT = Path(__file__).resolve().parents[1]

WHISPER_EXECUTABLE = (
    ROOT
    / "whisper.cpp"
    / "build"
    / "bin"
    / "whisper-cli"
)

WHISPER_MODEL = (
    ROOT
    / "whisper.cpp"
    / "models"
    / "ggml-tiny.en.bin"
)

JFK_AUDIO = (
    ROOT
    / "whisper.cpp"
    / "samples"
    / "jfk.wav"
)


class RealSpeechOutcomeExperiment:
    """
    Experiment dependency used to expose an explicit
    observed outcome to the cognitive experiment engine.

    The outcome is derived from the real Whisper
    transcription supplied during construction.

    No prediction is used to generate the outcome.
    """

    def __init__(self, transcription):
        if not isinstance(
            transcription,
            str
        ):
            raise TypeError(
                "transcription must be a string"
            )

        if not transcription.strip():
            raise ValueError(
                "transcription cannot be empty"
            )

        self.transcription = transcription

        self.observed_value = (
            len(transcription)
            + 20
        )

        self.received_hypothesis = None

    def run(
        self,
        observation,
        hypothesis=None
    ):
        """
        Return the explicit observed outcome.

        The outcome depends only on the real
        Whisper transcription and not on the
        current prediction.
        """

        self.received_hypothesis = (
            hypothesis
        )

        return self.observed_value


def create_real_speech_engine():
    """
    Create the real Whisper speech-recognition engine.

    This helper performs environment validation and
    dependency construction. It does not mock Whisper.
    """

    assert WHISPER_EXECUTABLE.is_file()
    assert WHISPER_MODEL.is_file()
    assert JFK_AUDIO.is_file()

    backend = WhisperCLIBackend(
        executable_path=WHISPER_EXECUTABLE,
        model_path=WHISPER_MODEL,
        timeout_seconds=120,
    )

    assert backend.is_configured()

    return SpeechRecognitionEngine(
        backend=backend
    )


def recognize_jfk_audio():
    """
    Run the real JFK audio through whisper.cpp.
    """

    speech = create_real_speech_engine()

    result = speech.recognize_file(
        JFK_AUDIO
    )

    assert result["status"] == (
        "recognized"
    )

    text = result["text"]

    assert isinstance(
        text,
        str
    )

    assert text.strip()

    assert (
        "fellow Americans" in text
    )

    assert (
        "what your country can do for you"
        in text
    )

    return result


def create_single_hypothesis_engine():
    """
    Create a bounded hypothesis planner with exactly
    one candidate.

    Using one hypothesis here is intentional.

    The purpose of this integration test is to verify
    prediction learning for the SAME hypothesis across
    two cycles, rather than testing hypothesis exploration.
    """

    hypothesis_engine = HypothesisEngine(
        max_hypotheses=1
    )

    return HypothesisPlanningEngine(
        hypothesis_engine=hypothesis_engine
    )


def create_real_speech_cognitive_engine(
    transcription
):
    """
    Create a CognitiveExperimentEngine configured for
    real speech-derived learning.
    """

    planner = (
        create_single_hypothesis_engine()
    )

    engine = CognitiveExperimentEngine(
        hypothesis_planner=planner
    )

    experiment = (
        RealSpeechOutcomeExperiment(
            transcription
        )
    )

    engine.experiment_loop.experiment = (
        experiment
    )

    return engine, experiment


