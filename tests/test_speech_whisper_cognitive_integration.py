def test_real_speech_reaches_difference_and_learning():
    """
    Verify the complete cognitive path:

    Real speech
        ↓
    Whisper
        ↓
    Perception
        ↓
    Prediction
        ↓
    Explicit actual outcome
        ↓
    Difference
        ↓
    Learning

    The actual outcome is intentionally supplied by
    the test. It is not generated by Whisper or the
    cognitive pipeline.
    """

    recognition = recognize_jfk_audio()

    pipeline = CognitivePipeline()

    actual = {
        "text": recognition["text"]
    }

    result = pipeline.run_with_actual(
        actual=actual,
        text=recognition["text"]
    )

    assert result["status"] == (
        "completed"
    )

    assert (
        result["observation"]["status"]
        == "observation_created"
    )

    assert (
        result["prediction"]["status"]
        == "predicted"
    )

    assert (
        result["comparison"]["status"]
        == "compared"
    )

    assert (
        result["learning"]["status"]
        == "learned"
    )

    assert (
        result["comparison"]["actual"]
        == actual
    )

    assert "difference" in (
        result["comparison"]
    )

    assert "result" in (
        result["learning"]
    )


def test_real_speech_learning_changes_next_prediction():
    """
    Step 64-B

    Prove that learning from a real Whisper-derived
    experiment outcome changes the prediction in the
    NEXT cycle for the SAME hypothesis.

    Flow:

    Real Whisper transcription
        ↓
    Numeric observation derived from transcription
        ↓
    First prediction
        ↓
    Explicit observed outcome
        ↓
    Prediction error
        ↓
    Adaptive hypothesis learning
        ↓
    Second prediction
        ↓
    Prediction changed

    The observed outcome does NOT depend on the prediction.
    """

    recognition = recognize_jfk_audio()

    transcription = recognition["text"]

    assert isinstance(
        transcription,
        str
    )

    assert transcription.strip()

    engine, experiment = (
        create_real_speech_cognitive_engine(
            transcription
        )
    )

    observation = len(
        transcription
    )

    expected_actual = (
        len(transcription)
        + 20
    )

    first_result = engine.run_cycle(
        goal_state={
            "goal": "continue_observation"
        },
        observation=observation
    )

    assert first_result["status"] == (
        "completed"
    )

    first_prediction = (
        first_result["prediction"]
    )

    first_actual = (
        first_result["actual"]
    )

    first_difference = (
        first_result["difference"]
    )

    selected_hypothesis = (
        first_result[
            "selected_hypothesis"
        ]
    )

    hypothesis_name = (
        selected_hypothesis[
            "hypothesis"
        ]
    )

    assert isinstance(
        hypothesis_name,
        str
    )

    assert first_prediction == (
        observation
    )

    assert first_actual == (
        expected_actual
    )

    assert first_difference == (
        expected_actual
        - observation
    )

    assert experiment.received_hypothesis == (
        selected_hypothesis
    )

    first_learning = (
        first_result[
            "hypothesis_prediction_learning"
        ]
    )

    assert first_learning["status"] == (
        "learned"
    )

    first_updated_prediction = (
        first_learning[
            "result"
        ]["prediction"]
    )

    expected_first_update = (
        observation
        + (
            0.5
            * (
                expected_actual
                - observation
            )
        )
    )

    assert first_updated_prediction == (
        expected_first_update
    )

    second_result = engine.run_cycle(
        goal_state={
            "goal": "continue_observation"
        },
        observation=observation
    )

    assert second_result["status"] == (
        "completed"
    )

    second_prediction = (
        second_result["prediction"]
    )

    second_actual = (
        second_result["actual"]
    )

    second_difference = (
        second_result["difference"]
    )

    second_hypothesis = (
        second_result[
            "selected_hypothesis"
        ]
    )

    assert second_hypothesis[
        "hypothesis"
    ] == hypothesis_name

    assert second_actual == (
        expected_actual
    )

    assert second_prediction == (
        first_updated_prediction
    )

    assert second_prediction != (
        first_prediction
    )

    assert second_difference == (
        expected_actual
        - first_updated_prediction
    )

    second_learning = (
        second_result[
            "hypothesis_prediction_learning"
        ]
    )

    assert second_learning[
        "status"
    ] == "learned"

    second_updated_prediction = (
        second_learning[
            "result"
        ]["prediction"]
    )

    expected_second_update = (
        first_updated_prediction
        + (
            0.5
            * (
                expected_actual
                - first_updated_prediction
            )
        )
    )

    assert second_updated_prediction == (
        expected_second_update
    )

    history = engine.get_history()

    assert len(history) == 2

    learned_hypotheses = (
        engine.get_learned_hypotheses()
    )

    assert len(
        learned_hypotheses
    ) >= 1

    learned_names = {
        item["hypothesis"]
        for item in learned_hypotheses
    }

    assert hypothesis_name in (
        learned_names
    )
